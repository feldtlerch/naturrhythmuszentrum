/// Output-absent production charges each new wrapper; interning-hit rows remain beside it.
/// Charges are incremental and each N-1 attempt checks complete graph rollback.
/// ´test:integration:trig-parity-absent-output-boundaries´
#[test]
fn trig_parity_absent_output_boundaries() -> TestResult {
    use crate::testing::trig_parity_work::absent_attempt;
    use nrz_cas::limits::BudgetKind;
    let resources = [
        BudgetKind::Work,
        BudgetKind::StagedPayloadBytes,
        BudgetKind::PayloadBytes,
        BudgetKind::Vertices,
        BudgetKind::Edges,
        BudgetKind::StagedVertices,
        BudgetKind::StagedEdges,
    ];
    for (input, work, costs, prefixes) in [
        (
            0,
            29985,
            [29948, 18259, 7699, 17, 36, 16, 36],
            [29981, 26852, 5200, 25863, 5200, 5200, 5200],
        ),
        (
            1,
            27458,
            [27421, 16979, 7200, 16, 33, 15, 33],
            [27454, 24529, 4174, 23540, 4174, 4174, 4174],
        ),
        (
            2,
            30003,
            [29966, 18259, 7702, 17, 36, 16, 36],
            [29999, 26869, 5202, 25880, 5202, 5202, 5202],
        ),
    ] {
        for ((resource, cost), prefix) in resources.into_iter().zip(costs).zip(prefixes) {
            let prior = if resource == BudgetKind::Work { 37 } else { 0 };
            assert_eq!(absent_attempt(input, resource, cost + prior)?, (true, work));
            assert_eq!(
                absent_attempt(input, resource, cost + prior - 1)?,
                (false, prefix)
            );
        }
    }
    Ok(())
}
