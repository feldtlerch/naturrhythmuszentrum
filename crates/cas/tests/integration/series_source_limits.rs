/// Order-six source representatives have independent cold and retained admission ceilings.
/// ´test:integration:series-source-object-admission´
#[test]
fn series_source_object_admission() -> TestResult {
    use crate::testing::series_work::{KINDS, attempt_values};
    let values = ["0", "1", "0", "-1/6", "0", "1/120"];
    for (warm, ceilings, prefixes) in [
        (
            false,
            [1_870, 7_619, 5_823, 13, 25, 13, 25, 7, 5, 6, 0],
            [
                1_765, 1_870, 1_870, 1_870, 1_870, 1_870, 1_870, 1_651, 37, 37, 0,
            ],
        ),
        (
            true,
            [1_870, 7_683, 113, 0, 10, 13, 25, 7, 5, 6, 0],
            [1_765, 150, 142, 0, 1_661, 150, 150, 1_651, 37, 37, 0],
        ),
    ] {
        for ((kind, ceiling), prefix) in KINDS.into_iter().zip(ceilings).zip(prefixes) {
            assert_eq!(
                attempt_values(warm, kind, ceiling, &values)?,
                (true, 1_870),
                "{warm} {kind:?}"
            );
            if ceiling > 0 {
                assert_eq!(
                    attempt_values(warm, kind, ceiling - 1, &values)?,
                    (false, prefix),
                    "{warm} {kind:?}"
                );
            }
        }
    }
    Ok(())
}

/// Complete source ceilings are literal observations with 37 prior Work and 113 retained bytes.
/// ´test:integration:series-source-complete-resource-boundaries´
#[test]
fn series_source_complete_resource_boundaries() -> TestResult {
    for (mode, kind, ceilings, prefixes) in PINS {
        for (index, dimension) in crate::testing::series_boundaries::KINDS
            .into_iter()
            .enumerate()
        {
            assert!(
                crate::testing::series_source_work::attempt(
                    *mode,
                    *kind,
                    dimension,
                    ceilings[index]
                )?
                .0,
                "source {mode}/{kind} {dimension:?}"
            );
            if ceilings[index] > 0 {
                assert_eq!(
                    crate::testing::series_source_work::attempt(
                        *mode,
                        *kind,
                        dimension,
                        ceilings[index] - 1
                    )?,
                    (false, prefixes[index]),
                    "source {mode}/{kind} {dimension:?}"
                );
            }
        }
    }
    Ok(())
}

